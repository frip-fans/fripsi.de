const messages: Record<Locale, Record<TranslationKey, string>> = { "zh-CN": zhCN, "zh-TW": zhTW, ja, en };

export function isLocale(value: string | null | undefined): value is Locale {
  return supportedLocales.includes(value as Locale);
}

function cookieValue(header: string | null, name: string): string | undefined {
  for (const part of header?.split(";") ?? []) {
    const [key, ...value] = part.trim().split("=");
    if (key === name) return decodeURIComponent(value.join("="));
  }
  return undefined;
}

export function getLocale(request: Request): Locale {
  const queryLocale = new URL(request.url).searchParams.get("lang");
  if (isLocale(queryLocale)) return queryLocale;
  const saved = cookieValue(request.headers.get("cookie"), LOCALE_COOKIE);
  return isLocale(saved) ? saved : DEFAULT_LOCALE;
}

export function t(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    messages[locale][key] ?? zhCN[key],
  );
}

export function formatMonthLabel(locale: Locale, month: string): string {
  return new Intl.DateTimeFormat(locale, { year: "numeric", month: "long", timeZone: "UTC" })
    .format(new Date(`${month}-01T00:00:00Z`));
}

export function formatMonthOption(locale: Locale, month: number): string {
  return new Intl.DateTimeFormat(locale, { month: "short", timeZone: "UTC" })
    .format(new Date(Date.UTC(2026, month - 1, 1)));
}

export function formatYearLabel(locale: Locale, year: number): string {
  return new Intl.DateTimeFormat(locale, { year: "numeric", timeZone: "UTC" })
    .format(new Date(Date.UTC(year, 0, 1)));
}
