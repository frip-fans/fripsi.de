// Regenerate packages/core/src/cjk-variants.ts from OpenCC data.
// Usage: npm i --no-save opencc-js@1.4.2 && node scripts/build-cjk-variant-map.mjs
// Every Japanese shinjitai, Traditional (OpenCC / Taiwan / Hong Kong) or Simplified form of a
// character folds to one Simplified key, so search text and queries written in any of them match.
import { writeFileSync } from "node:fs";
import * as OpenCC from "opencc-js";

const toSimplified = ["jp", "hk", "tw", "t"].map(from => OpenCC.Converter({ from, to: "cn" }));
const fold = (char) => toSimplified.reduce((value, convert) => convert(value), char);

const ranges = [[0x3400, 0x4dbf], [0x4e00, 0x9fff]];
const pairs = [];
for (const [start, end] of ranges) for (let code = start; code <= end; code++) {
  const char = String.fromCodePoint(code);
  let folded = fold(char);
  // Keep only one-to-one character folds and settle chains such as A→B→C on their final form.
  for (let i = 0; i < 4 && [...folded].length === 1 && fold(folded) !== folded; i++) folded = fold(folded);
  if ([...folded].length === 1 && folded !== char) pairs.push([char, folded]);
}

const output = `// Generated by scripts/build-cjk-variant-map.mjs from opencc-js@1.4.2 (OpenCC data, Apache-2.0).
// Do not edit by hand. Each pair maps a Japanese, Traditional or variant character to its Simplified search key.
export const CJK_VARIANT_SOURCE = ${JSON.stringify(pairs.map(([from]) => from).join(""))};
export const CJK_VARIANT_TARGET = ${JSON.stringify(pairs.map(([, to]) => to).join(""))};
`;
writeFileSync(new URL("../packages/core/src/cjk-variants.ts", import.meta.url), output);
console.log(`wrote ${pairs.length} character folds`);
