#!/usr/bin/env node
// Match local releases and release tracks to the Apple Music (iTunes) Japan catalog.
//
// Usage: node scripts/match-apple-music.mjs <sqlite-path> <out.sql> [report.json]
//
// Reads releases from a SQLite copy (read-only), queries the public iTunes
// Search API (country=jp, ~20 requests/minute), and writes INSERT statements
// for release_external_ids / release_track_external_ids. The SQL is reviewed
// and applied separately; this script never writes to a database.
import { DatabaseSync } from "node:sqlite";
import { writeFileSync } from "node:fs";

const [dbPath, outPath, reportPath] = process.argv.slice(2);
if (!dbPath || !outPath) {
  console.error("Usage: node scripts/match-apple-music.mjs <sqlite-path> <out.sql> [report.json]");
  process.exit(1);
}

const STOREFRONT = "jp";
const ARTIST_TERM = "fripSide";
const REQUEST_GAP_MS = 3200;
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
let lastRequest = 0;
async function itunes(path, params) {
  const wait = lastRequest + REQUEST_GAP_MS - Date.now();
  if (wait > 0) await sleep(wait);
  lastRequest = Date.now();
  const url = new URL(`https://itunes.apple.com/${path}`);
  for (const [key, value] of Object.entries({ country: STOREFRONT, ...params })) url.searchParams.set(key, String(value));
  const response = await fetch(url, { headers: { "user-agent": "fripsi.de catalog matcher" } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return (await response.json()).results;
}

/** Comparable form of a title: width-folded, lowercased, punctuation and edition suffixes removed. */
export function normalizeTitle(title) {
  return title
    .normalize("NFKC")
    .toLowerCase()
    .replace(/\s+-\s+(single|ep)$/u, "")
    .replace(/[（(][^（）()]*(盤|edition|商品|version)[^（）()]*[）)]/gu, "")
    .replace(/[\s\-‐−–—~〜:：／/・☆!！?？'’"“”.,、。×x]/gu, "");
}

const db = new DatabaseSync(dbPath, { readOnly: true });
const releases = db.prepare("SELECT id, slug, title, release_type, release_date FROM releases WHERE published = 1 ORDER BY release_date").all();
const tracksFor = db.prepare(`
  SELECT rt.id, rt.disc_number, rt.track_number, rt.display_title
  FROM release_tracks rt WHERE rt.release_id = ? ORDER BY rt.disc_number, rt.track_number
`);

const seed = await itunes("search", { term: ARTIST_TERM, entity: "musicArtist", limit: 5 });
const artist = seed.find((item) => item.artistName === ARTIST_TERM);
if (!artist) throw new Error("fripSide artist not found in the JP storefront");
const albums = (await itunes("lookup", { id: artist.artistId, entity: "album", limit: 200 })).filter((item) => item.wrapperType === "collection");
console.error(`Apple JP: ${albums.length} albums for artist ${artist.artistId}`);

const days = (a, b) => Math.abs(Date.parse(a) - Date.parse(b)) / 86_400_000;
const report = { matched: [], unmatched: [] };
const sql = ["-- Generated by scripts/match-apple-music.mjs; review before applying.", `-- ${new Date().toISOString()} storefront=${STOREFRONT}`];
const checkedAt = new Date().toISOString();
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;

for (const release of releases) {
  const key = normalizeTitle(release.title);
  const candidates = albums
    .filter((album) => normalizeTitle(album.collectionName) === key)
    .map((album) => ({ album, gap: release.release_date ? days(release.release_date, album.releaseDate.slice(0, 10)) : 0 }))
    .sort((a, b) => a.gap - b.gap);
  // A title shared by several catalog entries (re-issues, digital singles) must also agree on the date.
  const best = candidates.length === 1 ? candidates[0] : candidates.find((item) => item.gap <= 45);
  if (!best) {
    report.unmatched.push({ slug: release.slug, title: release.title, candidates: candidates.map((item) => item.album.collectionName) });
    continue;
  }
  const { album } = best;
  const songs = (await itunes("lookup", { id: album.collectionId, entity: "song" })).filter((item) => item.wrapperType === "track");
  const local = tracksFor.all(release.id);
  const byTitle = new Map();
  for (const song of songs) {
    const title = normalizeTitle(song.trackName);
    if (!byTitle.has(title)) byTitle.set(title, []);
    byTitle.get(title).push(song);
  }
  const sameShape = songs.length === local.length;
  let trackHits = 0;
  sql.push(`INSERT OR REPLACE INTO release_external_ids (release_id, provider, external_id, storefront, checked_at) VALUES (${quote(release.id)}, 'apple_music', ${quote(album.collectionId)}, '${STOREFRONT}', ${quote(checkedAt)});`);
  for (const track of local) {
    const positional = songs.find((song) => song.discNumber === track.disc_number && song.trackNumber === track.track_number);
    const titled = byTitle.get(normalizeTitle(track.display_title)) ?? [];
    // Prefer the same position when its title agrees, then a unique title, then position on an identical track count.
    const song = (positional && titled.includes(positional) ? positional : null)
      ?? (titled.length === 1 ? titled[0] : null)
      ?? (sameShape ? positional : null);
    if (!song) continue;
    trackHits += 1;
    sql.push(`INSERT OR REPLACE INTO release_track_external_ids (release_track_id, provider, external_id, storefront, checked_at) VALUES (${quote(track.id)}, 'apple_music', ${quote(song.trackId)}, '${STOREFRONT}', ${quote(checkedAt)});`);
  }
  report.matched.push({ slug: release.slug, title: release.title, apple: album.collectionName, appleId: album.collectionId, dateGapDays: Math.round(best.gap), tracks: `${trackHits}/${local.length}`, appleTracks: songs.length });
  console.error(`✓ ${release.title} → ${album.collectionName} (${trackHits}/${local.length})`);
}

// One transaction: a failure part-way leaves the database unchanged.
writeFileSync(outPath, `${[sql[0], sql[1], "BEGIN;", ...sql.slice(2), "COMMIT;"].join("\n")}\n`);
if (reportPath) writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
console.error(`Matched ${report.matched.length}/${releases.length} releases; SQL → ${outPath}`);
